import fs from 'node:fs'

const main = fs.readFileSync('src/main.tsx','utf8')
const stage = fs.readFileSync('src/arena-stage.css','utf8')
const runtime = fs.readFileSync('src/arena-stage.ts','utf8')
const cards = fs.readFileSync('src/arena-card-info.ts','utf8')
const must = (ok,msg) => { if(!ok) throw new Error(msg) }

must(main.includes("import './arena-stage.css'"), 'portrait Arena CSS is not imported')
must(main.includes("import './arena-stage.ts'"), 'portrait Arena runtime is not imported')
must(stage.includes('authoritative portrait blueprint 780 x 1110'), '780x1110 coordinate contract missing')
must(stage.includes('.mx-field-left .effect-rack'), 'left side effect rack missing')
must(stage.includes('.mx-field-right .effect-rack'), 'right side effect rack missing')
must(stage.includes('POSISI KAD'), 'position row contract missing')
must(stage.includes('.mx-card-inspector'), 'plain-text card inspector styling missing')
must(stage.includes('.mx-card-inspector__actions'), 'inspector action row missing')
must(stage.includes('.mx-zone-x-count'), 'Zon X score counter styling missing')
must(stage.includes('mxPhaseGlow'), 'phase-driven glow missing')
must(stage.includes('mxZoneScoreFlash'), 'Zon X score flash missing')
must(stage.includes('mxTargetPulse'), 'target pulse missing')
must(stage.includes('mxPlayConfirm'), 'play confirmation animation missing')
must(runtime.includes('CARD_INFO'), 'inspector is not backed by card data')
must(runtime.includes('data-mx-play'), 'overlay PLAY action missing')
must(runtime.includes('stopImmediatePropagation'), 'hand tap is not separated from play confirmation')
must(runtime.includes('mx-phase-target'), 'target phase marker missing')
must(runtime.includes('mx-score-changed'), 'score-change feedback missing')
must(runtime.includes('mx-deck-changed'), 'Master Deck feedback missing')
must((cards.match(/\bid:\d+/g) || []).length === 30, 'card inspector database must contain 30 cards')

console.log('PASS portrait Arena: blueprint geometry, overlay play flow, phase targeting and action feedback')

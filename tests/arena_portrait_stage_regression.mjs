import fs from 'node:fs'

const main = fs.readFileSync('src/main.tsx','utf8')
const fragment = fs.readFileSync('src/arena-blueprint.fragment','utf8')
const stage = fs.readFileSync('src/arena-stage.css','utf8')
const action = fs.readFileSync('src/arena-action.css','utf8')
const runtime = fs.readFileSync('src/arena-stage.ts','utf8')
const app = fs.readFileSync('src/App.tsx','utf8')
const must = (ok,msg) => { if(!ok) throw new Error(msg) }

must(main.includes("import './arena-stage.css'"), 'Arena 2 CSS is not imported')
must(main.includes("import './arena-action.css'"), 'Arena 2 action CSS is not imported')
must(main.includes("import './arena-stage.ts'"), 'Arena 2 runtime is not imported')
must(!main.includes('arena-real-phone.css'), 'legacy phone geometry is imported')
must(fragment.includes('mx2-arena'), 'Arena 2 root missing')
must((fragment.match(/mx2-vs-frame/g) || []).length >= 2, 'two new VS frames required')
must((fragment.match(/mx2-effect-rail/g) || []).length >= 2, 'two new Effect rails required')
must(fragment.includes('Array.from({ length: 5 }'), 'five-slot Effect structure missing')
must(fragment.includes('mx2-local-hand') && fragment.includes('mx2-opponent-hand'), 'new hand renderers missing')
must(fragment.includes('mx2-score-core') && fragment.includes('mx2-deck-core'), 'new counter/deck presentation missing')
must(fragment.includes('mx2-position-bar') && fragment.includes('mx2-stats'), 'new position/stat presentation missing')
must(fragment.includes('setVS(bottomPlayer, card.id') && fragment.includes('playEffect(bottomPlayer, card.id)'), 'new hand lost gameplay handlers')
must(fragment.includes('setPileView') && fragment.includes('setFocusedCard'), 'new zones lost inspect/pile handlers')
must(stage.includes('.mx2-effect-rail') && stage.includes('grid-template-rows:repeat(5'), 'new five-slot Effect geometry missing')
must(stage.includes('.mx2-vs-frame') && stage.includes('.mx2-score-core'), 'new VS/counter geometry missing')
must(action.includes('mx2Playable') && action.includes('mx2Score'), 'new action feedback missing')
must(runtime.includes("shell.classList.add('mx2-stage')"), 'Arena 2 runtime stage marker missing')
must(app.includes('mx2-arena'), 'generated App does not contain Arena 2')
must(!app.includes('<div className="arena-wrap">'), 'rendered legacy board survived')
must(!app.includes('<header className="fighter-hud">'), 'rendered legacy HUD survived')

console.log('PASS Arena 2: total new portrait presentation with preserved gameplay handlers')

import fs from 'node:fs'
const main=fs.readFileSync('src/main.tsx','utf8')
const stage=fs.readFileSync('src/arena-stage.css','utf8')
const action=fs.readFileSync('src/arena-action.css','utf8')
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'))
function assert(ok,msg){if(!ok)throw new Error(msg)}

assert(main.includes("import './arena-stage.css'"),'portrait coordinate stage is not loaded')
assert(main.includes("import './arena-action.css'"),'action motion layer is not loaded')
assert(stage.includes('authoritative portrait blueprint 780 x 1110'),'780x1110 portrait authority missing')
assert(stage.includes('aspect-ratio:780/1110'),'portrait stage does not preserve blueprint aspect ratio')
assert(stage.includes('width:min(100vw,calc(100dvh * 780 / 1110),780px)'),'stage is not uniformly scaled from portrait blueprint')
assert(stage.includes('POSISI KAD'),'VS position row contract missing')
assert(stage.includes('.effect-rack') && stage.includes('grid-template-rows:repeat(5'),'vertical five-slot Effect rack contract missing')
assert(stage.includes('.fighter-stats') && stage.includes('grid-template-columns:repeat(3'),'ATK/DEF/STA protected row missing')
assert(stage.includes('.hand-area') && stage.includes('top:82.70%'),'hand is not pinned to measured bottom zone')
assert(stage.includes('PURE OVERLAY'),'card inspector is not explicitly isolated as overlay')
assert(action.includes('visual feedback only. Never owns geometry'),'animation layer is allowed to own geometry')
assert(!pkg.scripts.build.includes('patch-arena-responsive-system.mjs'),'obsolete responsive geometry patch remains active')
assert(!pkg.scripts.build.includes('patch-responsive-arena.mjs'),'legacy responsive arena patch remains active')
assert(!pkg.scripts.build.includes('patch-mobile-arena-v2.mjs'),'legacy mobile arena patch remains active')
console.log('PASS Arena viewport uses one 780x1110 portrait coordinate authority with isolated motion layer')

import fs from 'node:fs'
const app=fs.readFileSync('src/App.tsx','utf8')
const audio=fs.readFileSync('src/audio.ts','utf8')
const assets=fs.readFileSync('src/audio-assets.ts','utf8')
const stage=fs.readFileSync('src/arena-stage.css','utf8')
const fragment=fs.readFileSync('src/arena-blueprint.fragment','utf8')
const main=fs.readFileSync('src/main.tsx','utf8')
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'))
const must=(ok,msg)=>{if(!ok)throw new Error(msg)}
must(pkg.scripts.build.includes('patch-production-jank-hotfix.mjs'),'production motion/audio hotfix missing')
must(!pkg.scripts.build.includes('patch-single-fight.mjs'),'obsolete FIGHT patch remains')
must(stage.includes('MEGA-X ARENA MX3'),'Arena MX3 stage is not authoritative')
must(fragment.includes('mx3-canvas')&&fragment.includes('mx3-local-hand'),'Arena MX3 fragment missing')
must(main.includes("import './arena-stage.css'")&&!main.includes('arena-action.css')&&!main.includes('arena-overlay.css'),'Arena MX3 must have one Arena stylesheet')
const requiredAssets=['card-selected.opus','card-draw.opus','effect-enter-field.opus','card-enter-vs.opus','card-attacking.opus','card-destroyed.opus','card-goes-to-zon-x.opus','prompt-needed.opus','win-lose-screen.opus']
for(const asset of requiredAssets) must(assets.includes(`/audio/replacements/${asset}`),`replacement audio asset missing: ${asset}`)
must(!assets.includes('player-win.opus'),'legacy player-win mapping remains')
must(assets.includes('SFX_REV'),'replacement SFX cache revision missing')
must(!assets.includes('arena-appear.opus'),'Arena-entry announcer-risk asset mapping remains')
must(!audio.includes('arenaAppear'),'Arena-entry announcer-risk playback remains')
must(!fs.existsSync('public/audio/replacements/fight.opus'),'FIGHT audio file remains in production tree')
must(!assets.includes('fight.opus'),'FIGHT announcer asset mapping remains')
must(!audio.includes("playSfx('fight')"),'FIGHT announcer playback remains')
must(!audio.includes('playVoice'),'legacy announcer playback remains')
must(audio.includes("kind === 'ENTER_VS') this.playSfx('vsEnter')"),'VS placement dedicated SFX mapping missing')
must(audio.includes("else if (kind === 'SUPPORT') this.playSfx('enter')"),'Effect entry SFX mapping missing')
must(!audio.includes("kind === 'ENTER_VS' || kind === 'SUPPORT'"),'VS placement still incorrectly uses Effect entry SFX')
must(fragment.includes("activeOnlineMatch ? game.effectTurn === onlineSession?.userId : game.effectTurn === bottomPlayer"),'UUID-correct online Effect prompt gate missing')
must(fragment.includes("activeOnlineMatch ? game.attackTurn === onlineSession?.userId : game.attackTurn === bottomPlayer"),'UUID-correct online Attack prompt gate missing')
must(fragment.includes("!activeOnlineMatch || game.firstPlayer === onlineSession?.userId"),'UUID-correct begin-round prompt gate missing')
must(stage.includes('width:200px!important;height:280px!important'),'5:7 VS card rendering missing')
must(stage.includes('height:90px!important'),'tall Effect rail slots missing')
must(stage.includes("url('/ui/vs.webp')")&&stage.includes('mx3VsFlarePulse'),'supplied VS artwork/lens flare missing')
must(stage.includes('mx3PromptBob'),'compact bobbing phase prompt missing')
must(stage.includes('contain:paint'),'opponent hand containment missing')
must(app.includes("new CustomEvent('mega-x:motion'"),'motion state does not dispatch gameplay audio events')
must(app.includes('CONFIRM DISCARD')&&app.includes('selectedDiscardIds'),'Spudur discard interaction missing')
console.log('PASS Arena MX3 final lock: UUID-correct online prompts, supplied VS art/flare, compact prompt, contained opponent hand, dedicated VS-entry SFX, one-shot result music, no FIGHT audio')
